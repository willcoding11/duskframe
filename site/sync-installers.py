#!/usr/bin/env python3
"""Copy installers/ into site/ so Pages serves <site>/install.sh and install.ps1,
and push branding/brand.env values into the lines marked '# @brand' and into
site/config.js (the single brand block the page reads).  Run before publishing."""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
site, inst = root / "site", root / "installers"

env = {}
for line in (root / "branding" / "brand.env").read_text(encoding="utf-8").splitlines():
    m = re.match(r'\s*(BRAND_\w+)="([^"]*)"', line)
    if m:
        env[m.group(1)] = m.group(2)

vals = {"NAME": env["BRAND_NAME"], "SLUG": env["BRAND_SLUG"],
        "USER": env["BRAND_GH_USER"], "REPO": env["BRAND_GH_REPO"]}
keys = {  # variable name in the scripts -> value
    "BRAND_NAME": vals["NAME"], "BRAND_SLUG": vals["SLUG"], "GH_USER": vals["USER"], "GH_REPO": vals["REPO"],
    "$BrandName": vals["NAME"], "$Slug": vals["SLUG"], "$GhUser": vals["USER"], "$GhRepo": vals["REPO"],
}

def stamp(text):
    out = []
    for ln in text.splitlines():
        if "# @brand" in ln:
            m = re.match(r'(\s*)(\$?\w+)(\s*=\s*)(["\'])[^"\']*\4(\s*#.*)$', ln)
            if m and m.group(2) in keys:
                ln = f'{m.group(1)}{m.group(2)}{m.group(3)}{m.group(4)}{keys[m.group(2)]}{m.group(4)}{m.group(5)}'
        out.append(ln)
    return "\n".join(out) + "\n"

for name in ("install.sh", "install.ps1"):
    src = inst / name
    src.write_bytes(stamp(src.read_text(encoding="utf-8")).encode())  # keep LF
    (site / name).write_bytes(src.read_bytes())

site_url = env.get("BRAND_SITE") or f"https://{vals['USER']}.github.io/{vals['REPO']}"
cfg = {**{k.lower(): v for k, v in vals.items()}, "site": site_url,
       "releases": f"https://github.com/{vals['USER']}/{vals['REPO']}/releases/latest/download",
       "repo_url": f"https://github.com/{vals['USER']}/{vals['REPO']}"}
(site / "config.js").write_text("// generated by sync-installers.py from branding/brand.env\n"
                                "window.BRAND = " + json.dumps(cfg, indent=2) + ";\n", encoding="utf-8")
print("synced:", ", ".join(["install.sh", "install.ps1", "config.js"]), "->", site)
